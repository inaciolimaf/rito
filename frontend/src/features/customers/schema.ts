import { z } from "zod";

export const customerFormSchema = z
  .object({
    type: z.enum(["PF", "PJ"]),
    name: z.string().min(1, "Nome é obrigatório."),
    origin_id: z.string().min(1, "Origem é obrigatória."),
    identification: z.string().optional(),
    document: z.string().optional(),
    notes: z.string().optional(),
    birthdate: z.string().optional(),
    marital_status_id: z.string().optional(),
    occupation: z.string().optional(),
    gender: z.enum(["F", "M", ""]).optional(),
    nationality: z.string().optional(),
    mother_name: z.string().optional(),
    cellphone: z.string().optional(),
    phone: z.string().optional(),
    email: z.string().optional(),
    country: z.string(),
    postal_code: z.string().optional(),
    state: z.string().optional(),
    city: z.string().optional(),
    street: z.string().optional(),
    region: z.string().optional(),
    number_pis: z.string().optional(),
    number_ctps: z.string().optional(),
    number_cid: z.string().optional(),
    has_representative: z.boolean(),
    rep_name: z.string().optional(),
    rep_identification: z.string().optional(),
    rep_document: z.string().optional(),
    rep_birthdate: z.string().optional(),
    rep_country: z.string().optional(),
    rep_state: z.string().optional(),
    rep_city: z.string().optional(),
    rep_street: z.string().optional(),
    rep_region: z.string().optional(),
    rep_postal_code: z.string().optional(),
  })
  .refine((values) => !values.has_representative || values.rep_name?.trim(), {
    message: "Nome do representante é obrigatório.",
    path: ["rep_name"],
  });

export type CustomerFormValues = z.infer<typeof customerFormSchema>;

